package org.example;

/**
 * Simple example application that prints a greeting and counts from 1 to 5.
 *
 * This class demonstrates basic Java syntax and control flow. It can be used
 * as a starting point for new developers learning the project structure.
 */
public class Main {

    public static void main(String[] args) {

        System.out.println("Hello Maven");

        for (int i = 1; i <= 5; i++) {
            System.out.println("i = " + i);
        }
    }
}
